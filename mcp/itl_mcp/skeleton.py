"""The citable half of a verdict, committed, and the check that keeps it honest.

A verdict is computed, so it exists only where the server runs. The study in
`docs/verdict-as-artefact.md` weighs committing it, and what is tried here is the
smaller half of that: the **skeleton** — the verdict, the Articles behind it, the
lookups, the silences and the hashes of every input — written to
`fixtures/verdicts/<treaty>.json` and readable by anything that can read a file,
including a reader that installs nothing.

Two things make it a control rather than a copy:

* **it is generated, never written by hand**, and a test compares the committed
  file with what this command writes, byte for byte, the way the corpus compares
  every derived artefact it commits;
* **it carries the hashes of the inputs it was computed from**, so the tool can
  see that the data has moved under it and refuse instead of answering from a
  file that no longer describes the data. What it must not do is answer *from*
  the file: nothing here is trusted for the verdict, and the reason a file is
  stale is reported, not repaired.

The inputs are named relative to the two checkouts (`corpus:...`, `library:...`)
and never by path: a committed file that described the machine it was built on
would be the trace invariant F14 exists to refuse.

There is no honesty without the price, and the price is stated where it is paid:
a corpus or library push that moves any of these files makes every skeleton stale
until the command is run again, and the tool refuses in the meantime.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

from .roots import Roots, load_roots
from .verdict import Undecidable, _load_position, as_modified

DIRECTORY = Path(__file__).resolve().parent.parent / "fixtures" / "verdicts"

NOTE = ("Generated by `python -m itl_mcp.skeleton --write`. Do not edit by hand: "
        "a value somebody typed can only ever be compared with what somebody "
        "typed, and this file is a control only while a command writes it.")


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _position_file(corpus: Path, party: str) -> Path | None:
    """Where a party's position document lives, by its own published slug."""
    payload = _load_position(corpus, party)
    if payload is None:
        return None
    slug = payload.get("slug")
    if not slug:
        return None
    path = corpus / "corpora" / "mli" / "positions" / f"{slug}.json"
    return path if path.is_file() else None


def _document(path: Path) -> dict:
    """The treaty file, read here rather than through the verdict's own reader.

    Reading it through `itl_mcp.artefacts` would couple this module to the
    reading of the answer it is checking; what it needs is the party names, and
    they are in the file.
    """
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def inputs(roots: Roots, treaty_id: str) -> dict[str, str]:
    """The bytes a verdict for this treaty was computed from, by digest.

    The treaty, the parties' position documents, the signatories table and the
    MLI mapping: seven files for the two treaties in the library, which is what
    the server's own footprint measurement finds for the verdicts. A party whose
    document the corpus does not hold is recorded as ``absent`` rather than
    omitted, so a document appearing later is a movement like any other.
    """
    found: dict[str, str] = {}
    treaty = roots.library / "treaties" / treaty_id / "treaty.json"
    found[f"library:treaties/{treaty_id}/treaty.json"] = (
        _digest(treaty) if treaty.is_file() else "absent")
    payload = _document(treaty) if treaty.is_file() else {}
    for party in payload.get("parties") or []:
        path = _position_file(roots.corpus, str(party))
        label = f"corpus:corpora/mli/positions/{path.stem}.json" if path else \
                f"corpus:corpora/mli/positions/{party}"
        found[label] = _digest(path) if path else "absent"
    for name in ("signatories-and-parties.json", "mapping.json"):
        path = roots.corpus / "corpora" / "mli" / name
        found[f"corpus:corpora/mli/{name}"] = _digest(path) if path.is_file() else "absent"
    return dict(sorted(found.items()))


def skeleton(roots: Roots, treaty_id: str) -> dict:
    """The citable skeleton of one treaty's verdict, computed live."""
    payload = as_modified(roots, treaty_id).as_dict()
    articles = []
    for article in payload.get("mli_articles") or []:
        articles.append({
            "mli_article": article.get("mli_article"),
            "title": article.get("title"),
            "mode": article.get("mode"),
            "mli_convention_page": article.get("mli_convention_page"),
            "targets_treaty_articles": article.get("targets_treaty_articles"),
            "recorded_by": article.get("recorded_by"),
        })
    lookups = []
    for lookup in payload.get("covered_agreement_lookups") or []:
        entry = lookup.get("entry") or {}
        lookups.append({
            "position_document_of": lookup.get("position_document_of"),
            "searched_for_state": lookup.get("searched_for_state"),
            "treaty_listed_as_covered": lookup.get("treaty_listed_as_covered"),
            "match_method": lookup.get("match_method"),
            "entry": {"no": entry.get("no"), "page": entry.get("page"),
                      "other_jurisdiction": entry.get("other_jurisdiction"),
                      "signature": entry.get("signature")} if entry else None,
        })
    return {
        "note": NOTE,
        "treaty": payload.get("treaty"),
        "title": payload.get("title"),
        "parties": payload.get("parties"),
        "pages": payload.get("pages"),
        "source_sha256": payload.get("source_sha256"),
        "verdict": payload.get("verdict"),
        "reasoning": payload.get("reasoning"),
        "articles": articles,
        "covered_agreement_lookups": lookups,
        "assumptions": payload.get("assumptions"),
        "constructed_links": payload.get("constructed_links"),
        "silences": payload.get("silences"),
        # What it was computed from, so a reader can see that it is not the data
        # and a tool can see that the data has moved.
        "inputs": inputs(roots, treaty_id),
    }


def text(payload: dict) -> str:
    """The bytes of a skeleton: one JSON object, one trailing newline."""
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def treaties(roots: Roots) -> list[str]:
    """Every treaty the library holds, in path order."""
    return sorted(path.parent.name
                  for path in (roots.library / "treaties").glob("*/treaty.json"))


def document(treaty_id: str, directory: Path | None = None) -> Path:
    return Path(directory or DIRECTORY) / f"{treaty_id}.json"


def read(treaty_id: str, directory: Path | None = None) -> dict | None:
    path = document(treaty_id, directory)
    if not path.is_file():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except ValueError:
        return None


def stale(roots: Roots, treaty_id: str, directory: Path | None = None) -> str | None:
    """Why the committed skeleton no longer describes the data, or ``None``.

    Not a repair: a stale skeleton names the input that moved, the digest it was
    computed from and the digest it has now, and says what to run. Nothing is
    recomputed into the file from here.
    """
    held = read(treaty_id, directory)
    if held is None:
        return None
    recorded = held.get("inputs") or {}
    now = inputs(roots, treaty_id)
    for label, digest in sorted(recorded.items()):
        current = now.get(label, "absent")
        if current != digest:
            return (f"the committed verdict for {treaty_id!r} is older than the "
                    f"data it was computed from: {label} was {digest[:12]} and is "
                    f"{current[:12] if current != 'absent' else 'now absent'}. "
                    f"Run `python -m itl_mcp.skeleton --write` with both roots "
                    f"named, and this answer comes back")
    for label, digest in sorted(now.items()):
        if label not in recorded:
            return (f"the committed verdict for {treaty_id!r} does not name every "
                    f"input the data now has: {label} ({digest[:12]}) was not read "
                    f"when it was computed. Run `python -m itl_mcp.skeleton --write`")
    return None


def refusal(reason: str) -> dict:
    """The answer the tool gives instead of a verdict it cannot stand behind."""
    return {
        "verdict": "stale",
        "reason": reason,
        "note": ("this is a real answer: the committed verdict is a claim about "
                 "these artefacts, and the artefacts have moved under it"),
    }


def write(roots: Roots, directory: Path | None = None) -> list[Path]:
    """Write every skeleton the library has a treaty for, and name the files."""
    target = Path(directory or DIRECTORY)
    target.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for treaty_id in treaties(roots):
        try:
            payload = skeleton(roots, treaty_id)
        except Undecidable:
            continue
        path = target / f"{treaty_id}.json"
        path.write_text(text(payload), encoding="utf-8")
        written.append(path)
    return written


def check(roots: Roots) -> list[str]:
    """The committed skeletons that are not what this command writes."""
    problems: list[str] = []
    for treaty_id in treaties(roots):
        path = document(treaty_id)
        if not path.is_file():
            problems.append(f"{path.name}: not committed (write it with "
                            f"`python -m itl_mcp.skeleton --write`)")
            continue
        try:
            wanted = text(skeleton(roots, treaty_id))
        except Undecidable as error:
            problems.append(f"{path.name}: the library no longer holds the "
                            f"treaty: {error.reason}")
            continue
        if path.read_text(encoding="utf-8") != wanted:
            problems.append(f"{path.name}: differs from what a computation "
                            f"writes now")
        reason = stale(roots, treaty_id)
        if reason:
            problems.append(f"{path.name}: {reason}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m itl_mcp.skeleton",
        description="Print, write or check the committed verdict skeletons.")
    parser.add_argument("--write", action="store_true",
                        help=f"write {DIRECTORY.name}/ (the only way it is written)")
    parser.add_argument("--check", action="store_true",
                        help="fail when a committed skeleton is not what a "
                             "computation writes, or is stale")
    parser.add_argument("--treaty", default=None,
                        help="one treaty id, instead of all of them")
    args = parser.parse_args(argv)

    roots = load_roots()
    if args.write:
        for path in write(roots):
            print(f"written: {path}")
        return 0
    if args.check:
        problems = check(roots)
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1 if problems else 0
    for treaty_id in ([args.treaty] if args.treaty else treaties(roots)):
        print(text(skeleton(roots, treaty_id)), end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
